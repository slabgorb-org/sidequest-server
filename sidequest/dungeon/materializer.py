@dataclass(frozen=True, slots=True)
class MaterializationRequest:
    """Frozen, hashable specification for one materialisation run.

    Construct via :meth:`build` — it runs the loud validation and coerces
    ``attach_region_ids`` from a ``list[str]`` to a ``tuple[str, ...]`` so the
    object stays genuinely hashable (lists are unhashable). The bare
    constructor is the dataclass-generated one (positional fields, no
    validation) and is used only internally by :meth:`build`.

    Validation rules (enforced by :meth:`build`, no silent defaults):
    - ``expansion_id >= 1`` — expansion 0 is reserved for the seed/entrance
      per the Seed = Expansion 0 contract; negative values are always invalid.
    - ``frontier_edge`` must appear (by ``frontier_edge_id``) in the supplied
      ``frontier`` list — proves the edge exists before the request is built.
    - ``burst_magnitude >= 1`` — a zero or negative burst is incoherent.

    ``frontier`` is a :meth:`build`-only validation parameter: it is never
    stored as a field and does not affect equality or hashing.
    """

    campaign_seed: int
    expansion_id: int
    frontier_edge: FrontierEdge
    attach_region_ids: tuple[str, ...]
    heading: str
    burst_magnitude: int
    lookahead_breadth: int
    # Story 55-1 / ADR-109: location of the world the materializer is
    # writing into. Optional (default empty) so older test call sites
    # remain valid; production callers (``session_integration`` →
    # ``build_expansion_one_request`` / ``lookahead_worker``) thread real
    # slugs so the post-commit YAML emit can resolve
    # ``<pack_root>/worlds/<world>``. Both must be non-empty to trigger
    # the emit; either empty is a clean no-op (matches the "tests don't
    # need to wire genre/world" contract).
    genre_slug: str = ""
    world_slug: str = ""
    # Track B (task 11): which per-``(session, site_id)`` dungeon store this run
    # writes into. Defaults to the frontier store (``DEFAULT_SITE_ID``) so every
    # existing frontier/lookahead caller is unchanged; a bounded-site request
    # threads its own ``site_id`` so its whole graph lands in that site's store.
    site_id: str = DEFAULT_SITE_ID

    @classmethod
    def build(
        cls,
        *,
        campaign_seed: int,
        expansion_id: int,
        frontier_edge: FrontierEdge,
        attach_region_ids: list[str] | tuple[str, ...],
        heading: str,
        burst_magnitude: int,
        lookahead_breadth: int,
        frontier: list[FrontierEdge],
        genre_slug: str = "",
        world_slug: str = "",
        site_id: str = DEFAULT_SITE_ID,
    ) -> MaterializationRequest:
        """Validate then build a frozen request. No silent defaults.

        ``frontier`` is consumed here only to prove ``frontier_edge`` is a live
        frontier member; it is never stored on the returned object.

        ``genre_slug`` / ``world_slug`` are optional (defaults empty) —
        a request that does NOT carry them is a request that does NOT
        emit room YAMLs. Production callers thread the real slugs;
        test fixtures that exercise only design/curate/attach/commit
        without the YAML-emit branch leave them empty.
        """
        if expansion_id < 1:
            raise ValueError(
                f"expansion_id must be >= 1 (expansion 0 is reserved for the "
                f"seed/entrance per the Seed=Expansion-0 contract); got {expansion_id!r}"
            )
        if burst_magnitude < 1:
            raise ValueError(
                f"burst_magnitude must be >= 1 (a zero/negative burst is "
                f"incoherent); got {burst_magnitude!r}"
            )
        if site_id != DEFAULT_SITE_ID and lookahead_breadth > 0:
            # Track B invariant (No Silent Fallbacks): only the frontier store
            # (DEFAULT_SITE_ID) runs a lookahead worker. A per-site store is
            # materialized WHOLE (lookahead_breadth == 0, no open frontier), so
            # a non-default site_id with lookahead > 0 is incoherent — the
            # commit stage's put_frontier writes to DEFAULT_SITE_ID and would
            # silently cross-contaminate the frontier store. Reject it loudly.
            raise ValueError(
                f"site_id {site_id!r} (non-frontier) requires lookahead_breadth == 0 "
                f"(a bounded site materializes whole, no frontier worker); "
                f"got lookahead_breadth={lookahead_breadth!r}"
            )
        frontier_ids = frozenset(fe.frontier_edge_id for fe in frontier)
        if frontier_edge.frontier_edge_id not in frontier_ids:
            raise ValueError(
                f"frontier_edge {frontier_edge.frontier_edge_id!r} is not in the "
                f"supplied frontier list (known ids: {sorted(frontier_ids)}). "
                f"A frontier_edge not present in the frontier cannot be expanded."
            )
        return cls(
            campaign_seed,
            expansion_id,
            frontier_edge,
            tuple(attach_region_ids),
            heading,
            burst_magnitude,
            lookahead_breadth,
            genre_slug,
            world_slug,
            site_id,
        )


