def _stage_design(
    request: MaterializationRequest,
    *,
    graph: RegionGraph | None,
    palette: ThemePalette | None,
    span: _otel_trace.Span,
    region_count: tuple[int, int] | None = None,
) -> tuple[Expansion, GenerationReport]:
    """Plan 7 Task 2: design stage — depth-filtered theme_pool + expansion generation.

    Depth-filters the palette via ``palette.themes_for_depth(depth_score)``
    (depth_score = ``request.frontier_edge.spawn_depth_score`` per the Seed=Expansion-0
    contract), calls ``generate_expansion``, and sets ``report.as_dict()`` as the
    exact span attribute set (byte-pinned GM-panel contract).

    ``region_count`` (ADR-157): a bounded site passes its archetype's
    ``(room_count_min, room_count_max)`` so the generated room count honors the
    archetype's declared budget instead of the frontier default
    ``new_regions_per_expansion``. ``None`` (the frontier path) leaves the
    ``JaquaysConfig`` default untouched — byte-identical to the pre-ADR-157 call.

    Invariants (No Silent Fallbacks):
    - ``graph`` and ``palette`` must be real objects — ``None`` is rejected loudly.
    - Empty theme_pool after filtering → loud ``ValueError`` (generation meaningless).
    - ``ExpansionGenerationError`` propagates unchanged — no retry with smaller burst,
      no swallowing.  The span carries a failure attribute before re-raise so the GM
      panel can see the failure (lie-detector visibility).
    """
    if graph is None:
        raise ValueError(
            "_stage_design requires a real RegionGraph — "
            "graph=None is not valid (No Silent Fallbacks)"
        )
    if palette is None:
        raise ValueError(
            "_stage_design requires a real ThemePalette — "
            "palette=None is not valid (No Silent Fallbacks)"
        )
    depth_score: float = request.frontier_edge.spawn_depth_score

    eligible_themes = palette.themes_for_depth(depth_score)
    if not eligible_themes:
        raise ValueError(
            f"No themes eligible at depth_score={depth_score!r} — theme_pool would be "
            f"empty, which makes expansion generation meaningless. "
            f"Check the depth_band definitions in the theme palette."
        )
    theme_pool: list[str] = [t.id for t in eligible_themes]

    config = (
        JaquaysConfig(connection_burst=request.burst_magnitude)
        if region_count is None
        else JaquaysConfig(
            connection_burst=request.burst_magnitude,
            new_regions_per_expansion=region_count,
        )
    )
    try:
        expansion, report = generate_expansion(
            graph=graph,
            campaign_seed=request.campaign_seed,
            expansion_id=request.expansion_id,
            attach_region_ids=list(request.attach_region_ids),
            theme_pool=theme_pool,
            config=config,
        )
    except ExpansionGenerationError as exc:
        # Lie-detector: mark the span with the failure before re-raising so the
        # GM panel sees it.  No swallowing, no retry-with-smaller-burst.
        span.set_attribute("error", str(exc))
        span.set_attribute("failing", json.dumps(exc.failing, sort_keys=True))
        raise

    # Byte-pinned span attribute contract: exactly report.as_dict() keys/values.
    # invariants_passed is a dict — serialise as JSON so OTEL can carry it.
    report_dict = report.as_dict()
    for k, v in report_dict.items():
        if isinstance(v, dict):
            span.set_attribute(k, json.dumps(v, sort_keys=True))
        else:
            span.set_attribute(k, v)

    # Story 158-37: the theme_pool above was gated by the SINGLE frontier
    # spawn_depth_score, but each new region's FINAL depth_score is computed
    # independently by assign_depth_scores at attach — AFTER the fill/curate
    # stages have already consumed the theme. So a region can be themed for the
    # frontier's depth and land at a depth its own depth_band excludes (the
    # exp011.r2 bone_crypt-at-8.2 playtest bug). Learn the final depths NOW, on a
    # throwaway clone (the real graph stays untouched until _stage_attach), and
    # re-resolve any band-violating region BEFORE fill/curate read the theme. The
    # real attach reproduces identical depths (same topology + campaign_seed), so
    # the correction holds end-to-end. Clone-not-mutate keeps _stage_attach's
    # byte-pinned depth_report contract intact (it still scores the new regions).
    depth_probe = RegionGraph.from_dict(graph.to_dict())
    attach_expansion(depth_probe, expansion)
    assign_depth_scores(depth_probe, campaign_seed=request.campaign_seed)
    theme_report = resolve_themes_for_final_depth(
        depth_probe,
        expansion,
        palette,
        campaign_seed=request.campaign_seed,
        expansion_id=request.expansion_id,
    )
    with dungeon_materialize_theme_resolve_span(
        expansion_id=request.expansion_id,
        resolved_count=theme_report.resolved_count,
        resolutions=json.dumps(theme_report.as_dict()["resolutions"], sort_keys=True),
    ):
        pass

    return expansion, report


def _stage_fill(
    request: MaterializationRequest,
    *,
    expansion: Expansion | None,
    palette: ThemePalette | None,
    span: _otel_trace.Span,
) -> dict[str, RegionFill]:
    """Plan 7 Task 3: fill stage — generate each region's interior grid.

    For every region node in ``expansion``, resolves its theme's interior
    algorithm + params + braid_ratio from ``palette`` and calls
    ``interiors.generate_interior``. Returns a ``dict`` mapping
    ``region_id -> RegionFill``; iteration order = ``expansion.new_nodes``
    order (dict insertion-order is a Python 3.7+ language guarantee). The
    ADR-055 ``rooms.yaml`` shape / ADR-096 mask sidecar serialization is
    consumed at Task 6 (commit), NOT here.

    Invariants (No Silent Fallbacks):
    - ``expansion`` and ``palette`` must be real objects — ``None`` is
      rejected loudly.
    - A region whose ``theme`` id is absent from ``palette.themes`` →
      loud ``ValueError`` (no skip, no default theme).
    - A roomcorridor region below ``ROOMCORRIDOR_MIN_DIM`` → loud
      ``ValueError`` naming the region/algorithm/dims/floor (the silent
      degenerate-rooms risk; no shrink/grow/skip).
    - A derived per-region seed equal to the braid fixed point
      (``0x5EED`` == 24301) → loud ``ValueError`` (would feed the braid
      sub-seed its degenerate fixed point).
    - An unknown algorithm raises via ``generate_interior``'s OWN guard
      (not re-implemented here) — it propagates unchanged.

    Any failure sets ``error`` on the span before raising so the GM panel
    sees the fill failure (lie-detector visibility) — no swallowing.
    """
    if expansion is None:
        raise ValueError(
            "_stage_fill requires a real Expansion — "
            "expansion=None is not valid (No Silent Fallbacks)"
        )
    if palette is None:
        raise ValueError(
            "_stage_fill requires a real ThemePalette — "
            "palette=None is not valid (No Silent Fallbacks)"
        )

    fills: dict[str, RegionFill] = {}
    try:
        for node in expansion.new_nodes:
            if node.theme not in palette.themes:
                raise ValueError(
                    f"region {node.id!r} references theme {node.theme!r} which "
                    f"is absent from the palette (have: "
                    f"{sorted(palette.themes)}). No silent default theme."
                )
            theme = palette.themes[node.theme]
            algorithm = theme.interior.algorithm
            braid_ratio = theme.interior.braid_ratio
            params = theme.interior.params
            width = DEFAULT_INTERIOR_WIDTH
            height = DEFAULT_INTERIOR_HEIGHT

            # roomcorridor degenerate-rooms floor (carry-forward): loud, no
            # shrink/grow/skip. Other algorithms rely on generate_interior's
            # own loud too-small guard.
            if algorithm == "roomcorridor" and (
                width < ROOMCORRIDOR_MIN_DIM or height < ROOMCORRIDOR_MIN_DIM
            ):
                raise ValueError(
                    f"region {node.id!r} algorithm 'roomcorridor' dims "
                    f"{width}x{height} are below ROOMCORRIDOR_MIN_DIM="
                    f"{ROOMCORRIDOR_MIN_DIM} (the room-placement retry loop "
                    f"degenerates to sparse/empty rooms below this floor). "
                    f"No silent shrink/grow/skip."
                )

            seed = _region_interior_seed(request.campaign_seed, request.expansion_id, node.id)
            # Degenerate-seed guard (carry-forward): generate_interior's braid
            # sub-seed is seed ^ 0x5EED → 0 at the fixed point. Refuse it loudly.
            if seed == _BRAID_FIXED_POINT:
                raise ValueError(
                    f"region {node.id!r} derived interior seed equals the braid "
                    f"fixed point 0x5EED ({_BRAID_FIXED_POINT}); the braid "
                    f"sub-seed (seed ^ 0x5EED) would degenerate to 0. Refusing "
                    f"to feed the braid its fixed point (No Silent Fallbacks)."
                )

            grid = generate_interior(
                algorithm,
                width=width,
                height=height,
                seed=seed,
                braid_ratio=braid_ratio,
                params=params or None,
            )
            # Story 52-2: emit the ADR-096 mask + derived block here, inside
            # the live dungeon.materialize.fill span context so the mask span
            # nests under it. _emit_mask is loud on empty grids (No Silent
            # Fallbacks); we let the ValueError propagate to the outer
            # try/except so the fill span carries the failure marker.
            mask = _emit_mask(grid)
            with dungeon_materialize_mask_span(
                region_id=node.id,
                grid_width=mask.block.grid_width,
                grid_height=mask.block.grid_height,
                cell_width=mask.block.cell_width,
                mask_sha=mask.mask_sha,
            ):
                pass
            fills[node.id] = RegionFill(
                region_id=node.id,
                algorithm=algorithm,
                width=width,
                height=height,
                braid_ratio=braid_ratio,
                grid=grid,
                mask=mask,
            )
    except ValueError as exc:
        # Lie-detector: surface the fill failure on the span before re-raise
        # so the GM panel sees it. No swallowing, no retry, no skip.
        span.set_attribute("error", str(exc))
        raise

    # Lie-detector success payload: the ACTUALLY-applied algorithm + dims +
    # braid_ratio per region (proving braid_ratio was not silently defaulted).
    regions_payload = [
        {
            "region_id": rf.region_id,
            "algorithm": rf.algorithm,
            "width": rf.width,
            "height": rf.height,
            "braid_ratio": rf.braid_ratio,
        }
        for rf in fills.values()
    ]
    span.set_attribute("regions", json.dumps(regions_payload, sort_keys=True))
    span.set_attribute("region_count", len(fills))

    return fills


class CurationError(RuntimeError):
    """A structurally-invalid *assembled* manifest reached the curate stage.

    ADR-106 Amendment C carve-out (i): a wandering row missing ``cr`` or an
    unknown ``cr_band`` big_bad is a real upstream content bug. Raised loudly
    so the materialization transaction aborts — there is no fallback that
    ships a corrupt manifest as content (No Silent Fallbacks). The curate span
    carries ``curated=false`` + a specific ``reason`` before this propagates so
    the GM panel sees it.
    """


def _resolve_look_for_theme(bundle: CookbookBundle, theme: Any, *, region_id: str) -> str:
    """Resolve a region's cookbook LOOK from its theme (the look→theme seam).

    `assemble_region` requires a ``look`` (a ``LookDef`` id). There is no
    ``look`` on ``DungeonTheme`` and none on ``MaterializationRequest`` /
    §12 knobs. The join key found by reconcile: a ``LookDef`` carries
    ``generator_binding`` (``depthfirst``/``cellular``/``prim``) and a
    ``DungeonTheme`` carries ``interior.algorithm`` — they are the SAME
    generator-family id. So a region's look is the LookDef whose
    ``generator_binding`` equals the region theme's ``interior.algorithm``.

    Fail loud (No Silent Fallbacks): if no look binds the theme's
    algorithm (e.g. a ``roomcorridor`` theme with no ``roomcorridor`` look
    in the shipped beneath_sunden ``looks.yaml``) raise a ``ValueError``
    naming the region/theme/algorithm. Never default to ``looks[0]``.
    """
    algorithm = theme.interior.algorithm
    matches = [lk.id for lk in bundle.looks if lk.generator_binding == algorithm]
    if not matches:
        raise ValueError(
            f"region {region_id!r} theme {theme.id!r} interior.algorithm "
            f"{algorithm!r} has no cookbook LOOK whose generator_binding "
            f"matches it (looks: "
            f"{ {lk.id: lk.generator_binding for lk in bundle.looks} }). "
            f"No silent fallback to looks[0] — author a look for this "
            f"generator family or retheme the region."
        )
    if len(matches) > 1:
        raise ValueError(
            f"region {region_id!r} theme {theme.id!r} algorithm {algorithm!r} "
            f"is bound by multiple looks {sorted(matches)} — ambiguous "
            f"look→theme seam; the cookbook must bind one look per "
            f"generator family. No silent first-match."
        )
    return matches[0]


def _creatures_from_manifest(
    manifest: RegionContentManifest, bundle: CookbookBundle
) -> tuple[list[CuratedCreature], CuratedCreature | None]:
    """ADR-106 Amendment C — the deterministic curate MAIN path: CR→Edge
    translate the seeded ``assemble_region`` manifest itself (clause 9 — valid,
    complete, seed-reproducible). Sourced from the manifest (no LLM verdict). The
    same payload Amendment A used only on its Layer-2 degrade is now the ONLY
    curate path.

    A manifest row/big_bad that cannot CR→Edge translate is the RETAINED
    ``CurationError`` carve-out (i): the assembled input is itself structurally
    invalid — a real upstream content bug; fail loud, never ship a corrupt input.
    """
    creatures: list[CuratedCreature] = []
    for row in manifest.wandering_table:
        if "cr" not in row:
            raise CurationError(
                f"assembled manifest wandering row {row!r} has no 'cr' — "
                f"the assembled manifest is itself invalid (carve-out i); "
                f"fail loud, never ship a corrupt input"
            )
        creatures.append(
            CuratedCreature(
                name=str(row["name"]),
                creature_type=str(row.get("type", "")),
                telegraph=str(row.get("telegraph", "")),
                hp=_hp_from_cr(float(row["cr"])),
                threat_level=_threat_from_band(bundle, manifest.cr_band),
            )
        )
    big_bad: CuratedCreature | None = None
    if manifest.big_bad is not None:
        bb_cr = None
        if isinstance(manifest.big_bad, dict):
            bb_cr = manifest.big_bad.get("cr")
        if bb_cr is None:
            band = next(
                (b for b in bundle.affinities.cr_bands if b.id == manifest.cr_band),
                None,
            )
            if band is None:
                raise CurationError(
                    f"assembled manifest big_bad has no cr and cr_band "
                    f"{manifest.cr_band!r} is not in affinities.cr_bands — "
                    f"the assembled manifest is itself invalid (carve-out i)"
                )
            bb_cr = band.cr_max
        bb_src = manifest.big_bad if isinstance(manifest.big_bad, dict) else {}
        big_bad = CuratedCreature(
            name=str(bb_src.get("name", "")),
            creature_type="big_bad",
            telegraph=str(bb_src.get("min_band", "")),
            hp=_hp_from_cr(float(bb_cr)),
            threat_level=min(4, _threat_from_band(bundle, manifest.cr_band) + 1),
        )
    return creatures, big_bad


def _append_authored_creatures(
    creatures: list[CuratedCreature],
    *,
    region_id: str,
    pack: Any,
    world_slug: str,
) -> list[CuratedCreature]:
    """Surface a region's AUTHORED ``rooms/<id>.yaml`` ``encounter_creatures``
    binding (Story 153-26; ADR-106 Amendment C: this runs on the deterministic
    curate MAIN path, for every region — not a degrade fallback).

    ``_creatures_from_manifest`` translates only the PROCEDURAL
    ``assemble_region`` manifest, so without this step authored encounters
    (``entrance`` → ``gnaw_swarm``) would never surface. ``resolve_room_creatures``
    is the LLM-free authored-binding read shared with the runtime Monster Manual
    seam (it emits ``monster_manual.room_bound``); consulting it here makes
    authored content join the deterministic procedural roster.

    A region with no authored binding (the common procedural case) is returned
    unchanged. ``pack=None`` / blank ``world_slug`` (test/bootstrap inputs with no
    world context) is a no-op — NOT a silent fallback, just an absent binding.

    A binding referencing an unknown bestiary id (or a world with no bestiary at
    all) is an AUTHORING error: ``resolve_room_creatures`` raises
    ``RoomCreatureBindingError``. On THIS path that error must stay LOUD-but-
    GRACEFUL: it is caught, logged at ERROR, and surfaced on the
    ``dungeon.curate.authored_bind_failed`` span, then curate PROCEEDS with the
    procedural roster (the turn proceeds, no table freeze). Letting it propagate
    would crash the player-facing bootstrap ``await materialize()`` at connect for
    a single content typo (Reviewer 153-26 HIGH).
    """
    if pack is None or not world_slug:
        return creatures
    # Local import: avoid an import-time cycle through the server.dispatch
    # package (the same lazy-import idiom as monster_manual_inject's caller).
    from sidequest.server.dispatch.room_creature_binding import (
        RoomCreatureBindingError,
        resolve_room_creatures,
    )

    try:
        bound_ids = resolve_room_creatures(pack, world_slug, region_id)
    except RoomCreatureBindingError as exc:
        # Loud-but-graceful: curate is already shipping the procedural roster —
        # a broken authored binding must NOT additionally crash the connect.
        # Surface it (ERROR log + GM-panel span) and proceed with the procedural
        # creatures.
        logger.error(
            "dungeon curate: authored room binding for region=%s "
            "world=%s could not be resolved (%s); shipping the procedural roster "
            "only — authored encounter dropped (ADR-106 Amendment C: loud-but-"
            "graceful on the main path, the turn proceeds, no table freeze)",
            region_id,
            world_slug,
            exc,
        )
        with dungeon_curate_authored_bind_failed_span(
            region_id=region_id, world_slug=world_slug, error=str(exc)
        ):
            pass
        return creatures
    if not bound_ids:
        return creatures
    bestiary, _ = pack.effective_bestiary(world_slug)
    by_id = {entry.id: entry for entry in (bestiary.entries if bestiary else [])}
    existing_names = {c.name for c in creatures}
    merged = list(creatures)
    for cid in bound_ids:
        entry = by_id.get(cid)
        if entry is None:
            # resolve_room_creatures already validated referential integrity
            # against this same effective_bestiary, so a miss here means the two
            # reads diverged (effective_bestiary is pure — should be impossible).
            # Log LOUD for observability rather than dropping it silently.
            logger.error(
                "dungeon curate: authored binding id=%s for region=%s "
                "resolved by resolve_room_creatures but is absent from the "
                "effective bestiary — dropping (divergent bestiary read?)",
                cid,
                region_id,
            )
            continue
        if entry.name in existing_names:
            # A name match means the procedural manifest already shipped it.
            continue
        merged.append(
            CuratedCreature(
                name=entry.name,
                creature_type=str(getattr(entry, "role", "") or "authored"),
                telegraph=str(getattr(entry, "description", "") or ""),
                hp=hp_pool_from_hp(int(entry.hp)),
                threat_level=int(getattr(entry, "level", 1) or 1),
            )
        )
        existing_names.add(entry.name)
    return merged


def _stage_curate(
    request: MaterializationRequest,
    *,
    bundle: CookbookBundle | None,
    palette: ThemePalette | None,
    expansion: Expansion | None,
    fill_result: dict[str, RegionFill] | None,
    is_first_band_entry: bool,
    span: _otel_trace.Span,
    pack: Any = None,
) -> RegionCuration:
    """ADR-106 Amendment C: deterministic curate stage — NO LLM.

    Generation proposes; the seed disposes. For every region in the
    expansion: derive its cookbook LOOK from its theme (the resolved
    look→theme seam), call the pure deterministic
    ``cookbook.assemble_region`` (campaign_seed/expansion_id int→str at
    this seam — DIVERGENCE 1), then CR→Edge translate the seeded manifest
    directly via ``_creatures_from_manifest`` and surface the authored
    ``rooms/<id>.yaml`` ``encounter_creatures`` binding via
    ``_append_authored_creatures``. This is the Amendment-A Layer-2 payload
    promoted to the ONLY path: materialization is pure-deterministic and
    seed-reproducible end-to-end. The live narrator owns creature prose at
    narration time (the deterministic ``telegraph`` is its hint), so the
    former Haiku ``complete_with_tools`` curate call — and the whole
    retry/deadline/degrade ladder that existed only to survive it — are
    deleted. Every corpus creature crossing the seam (wandering rows AND
    big_bad) is CR→Edge translated via the canonical ``hp_pool_from_hp`` —
    no raw cr/hp leaks into the curate-stage OUTPUT.

    Synchronous (Amendment C): with no coroutine to await, the curate stage
    is plain seeded compute. ``materialize`` calls it without ``await``.

    Invariants (No Silent Fallbacks):
    - ``bundle``/``palette``/``expansion`` must be real objects — ``None``
      is rejected loudly.
    - A region's cookbook LOOK is ALWAYS derived loudly from its theme
      (``_resolve_look_for_theme`` — an unresolved look is a loud
      ``ValueError``; NEVER a ``looks[0]`` default; a multi-bind is also
      a loud ``ValueError``). There is no caller ``look`` override:
      the theme is the single source of truth.
    - ``is_first_band_entry`` is an EXPLICIT threaded input — true
      band-entry history needs Plan 5 persistence (``load_frontier`` /
      ``load_map``) the curate stage does NOT own. Computing it from
      incomplete state here would be a silent fallback; the commit stage
      owns the real band-entry-history computation. (Reconcile seam:
      ``is_first_band_entry``.)
    - A structurally-invalid *assembled* manifest (a wandering row missing
      ``cr``, an unknown ``cr_band`` big_bad) raises a loud ``CurationError``
      (carve-out (i)) — a real upstream content bug is never degraded into
      shipped content. The span records ``curated=false`` + a specific
      ``reason`` before the raise (lie-detector visibility).
    """
    if bundle is None:
        raise ValueError(
            "_stage_curate requires a real CookbookBundle — "
            "bundle=None is not valid (No Silent Fallbacks)"
        )
    if palette is None:
        raise ValueError(
            "_stage_curate requires a real ThemePalette — "
            "palette=None is not valid (No Silent Fallbacks)"
        )
    if expansion is None:
        raise ValueError(
            "_stage_curate requires a real Expansion — "
            "expansion=None is not valid (No Silent Fallbacks)"
        )
    if fill_result is None:
        # Required to enforce fill-ran-before-curate pipeline ordering;
        # consumed at Task 6 (commit), not read in this stage's body.
        raise ValueError(
            "_stage_curate requires the fill stage result — "
            "fill_result=None is not valid (No Silent Fallbacks)"
        )

    campaign_seed_s = str(request.campaign_seed)  # DIVERGENCE 1: int→str seam
    expansion_id_s = str(request.expansion_id)  # DIVERGENCE 1: int→str seam
    depth_score = request.frontier_edge.spawn_depth_score

    manifests: dict[str, RegionContentManifest] = {}
    region_look: dict[str, str] = {}
    region_creatures: dict[str, list[CuratedCreature]] = {}
    region_big_bad: dict[str, CuratedCreature | None] = {}
    try:
        for node in expansion.new_nodes:
            if node.theme not in palette.themes:
                raise ValueError(
                    f"region {node.id!r} references theme {node.theme!r} "
                    f"which is absent from the palette (have: "
                    f"{sorted(palette.themes)}). No silent default theme."
                )
            theme = palette.themes[node.theme]
            # The look→theme seam: a region's cookbook LOOK is derived
            # loudly from its theme — the theme is the single source of
            # truth (No Silent Fallbacks — an unresolved or multi-bound
            # look raises in _resolve_look_for_theme; never a looks[0]
            # default, never a first-match).
            resolved_look = _resolve_look_for_theme(bundle, theme, region_id=node.id)
            region_look[node.id] = resolved_look
            manifest = assemble_region(
                bundle,
                campaign_seed=campaign_seed_s,
                expansion_id=expansion_id_s,
                depth_score=depth_score,
                burst_magnitude=request.burst_magnitude,
                look=resolved_look,
                is_first_band_entry=is_first_band_entry,
                # Story 55-1 / ADR-109: per-room deterministic seed
                # threaded from the materialized RegionNode id (v1: one
                # region = one room per ADR-106; the seam is open for a
                # future multi-room-per-region extension).
                room_id=node.id,
                # Task 9 (reference-pages v2): thread pack/world so each
                # LocationEntity in the manifest receives a reference_url.
                # request.genre_slug / world_slug default to "" when the
                # caller is a test fixture that doesn't carry world context;
                # passing "" is equivalent to None for the URL-builder guard.
                pack_id=request.genre_slug or None,
                world_slug=request.world_slug or None,
            )
            manifests[node.id] = manifest
            # ADR-106 Amendment C: deterministic curate — CR→Edge translate
            # the seeded manifest directly (the Amendment-A Layer-2 payload,
            # now the ONLY path), then surface the authored rooms/<id>.yaml
            # encounter_creatures binding. No LLM, no degrade ladder.
            creatures, big_bad = _creatures_from_manifest(manifest, bundle)
            creatures = _append_authored_creatures(
                creatures,
                region_id=node.id,
                pack=pack,
                world_slug=request.world_slug,
            )
            region_creatures[node.id] = creatures
            region_big_bad[node.id] = big_bad
    except ValueError as exc:
        # ValueError covers all three region-build sources: a theme absent from
        # the palette, an unresolved/multi-bound look (_resolve_look_for_theme),
        # and assemble_region itself — so the prefix is "region-build", not the
        # narrower "assemble" (Reviewer 158-12 LOW: GM-panel legibility).
        span.set_attribute("curated", False)
        span.set_attribute("reason", f"region-build: {exc}")
        raise
    except CurationError as exc:
        # Carve-out (i): a structurally-invalid *assembled* manifest is a
        # real upstream content bug — fail loud, never degrade into shipped
        # content (ADR-106 Amendment C / No Silent Fallbacks). Record the
        # lie-detector marker before the raise propagates and aborts the txn.
        span.set_attribute("curated", False)
        span.set_attribute("reason", f"invalid manifest: {exc}")
        raise
    except Exception as exc:
        # Any OTHER unexpected failure (e.g. a malformed homebrew pack object
        # whose effective_bestiary misbehaves) must STILL tag the curate span
        # before it propagates and aborts the txn — the GM-panel lie-detector
        # must never go dark on an error path (OTEL principle / No Silent
        # Fallbacks; consistent with the typed handlers above). Reviewer 158-12
        # MEDIUM: the typed handlers tag-before-raise; an unexpected exception
        # left the span untagged.
        span.set_attribute("curated", False)
        span.set_attribute("reason", f"unexpected: {exc}")
        raise

    # ADR-106 Amendment C: lie-detector summary on the curate STAGE span.
    # Deterministic ⇒ always curated; the failure-span taxonomy is retired.
    total_creatures = sum(len(v) for v in region_creatures.values())
    races = sorted({m.race for m in manifests.values()})
    bands = sorted({m.cr_band for m in manifests.values()})
    span.set_attribute("curated", True)
    span.set_attribute("region_count", len(manifests))
    span.set_attribute("creature_count", total_creatures)
    span.set_attribute("manifest_race", json.dumps(races, sort_keys=True))
    span.set_attribute("cr_band", json.dumps(bands, sort_keys=True))
    span.set_attribute("raw_seed_reproducible", True)

    return RegionCuration(
        region_manifests=manifests,
        region_creatures=region_creatures,
        region_big_bad=region_big_bad,
        region_look=region_look,
        curated=True,
        raw_seed_reproducible=True,
        uncurated_regions=frozenset(),
    )


@dataclass(frozen=True, slots=True)
class AttachResult:
    """In-memory result of the attach stage (Plan 7 Task 5).

    A frozen, slotted value object — same idiom as Task 1's
    ``MaterializationRequest`` / Task 3's ``RegionFill`` / Task 4's
    ``RegionCuration``. Carries the two things Task 6 (commit) needs and
    must NEVER recompute (spec §7 save-is-truth freeze):

    * ``depth_report`` — the :class:`DepthReport` from
      ``assign_depth_scores`` (the byte-pinned ``dungeon.materialize.attach``
      span contract; the depth_score gradient is already frozen onto
      ``graph.nodes`` in place — this is the summary report).
    * ``attach_reports`` — one :class:`AttachReport` per (region, set_piece)
      that was attached. Each carries ``report.rolled`` (a
      ``RolledSetPiece``) — the spec §7 FREEZE TARGET Task 6 persists into
      the save and NEVER recomputes from seed.

    Note: ``frozen`` blocks field reassignment but ``attach_reports`` is a
    mutable list; treat it as read-only by convention (same
    false-immutability caveat as ``RegionFill.grid`` /
    ``RegionCuration``'s dict fields).

    The attach stage does NOT commit and does NOT roll back — Task 6 owns
    the transaction boundary (spec §7.5). Threads written by
    ``attach_set_piece`` live in the caller's UNCOMMITTED connection.
    """

    depth_report: DepthReport
    attach_reports: list[AttachReport]


def _stage_attach(
    request: MaterializationRequest,
    *,
    graph: RegionGraph | None,
    expansion: Expansion | None,
    palette: ThemePalette | None,
    curation: RegionCuration | None,
    snapshot: GameSnapshot | None,
    pack_tropes: Any,
    tx: DungeonTransaction | None,
    span: _otel_trace.Span,
) -> AttachResult:
    """Plan 7 Task 5: attach stage — region-graph attach + depth scoring +
    the Plan 6 set-piece / trope / quest seam.

    Ordering (the plan owns this — Plan 6/5 spans nest INSIDE this span):
      1. ``attach_expansion(graph, expansion)`` — mutates + re-verifies the
         GLOBAL connected + loopful invariants. If it raises (a global
         invariant violation), the WHOLE materialization aborts: NO depth
         scoring, NO set-piece attach, NO partial state. The failure marker
         is routed onto the span before re-raise (lie-detector visibility).
      2. ``assign_depth_scores(graph, campaign_seed=...)`` → ``DepthReport``.
         The entrance scores to EXACTLY ``0.0`` (no jitter at the origin);
         an already-scored region is FROZEN (never recomputed — the save is
         truth, spec §7; ``assign_depth_scores`` enforces this). The span's
         attributes are set to EXACTLY ``DepthReport.as_dict()``'s 4 keys
         (byte-pinned GM-panel contract — NOT ``AttachReport``; that is
         Plan 6's nested ``setpiece.attach`` span).
      3. For every region in ``expansion.new_nodes``, resolve
         ``theme = palette.themes[node.theme]`` (loud raise if absent — no
         silent default theme) and for every ``set_piece in
         theme.set_pieces`` call Plan 6's single coalescence entry point
         ``attach_set_piece(...)`` with ``started_at_depth_score`` = the
         region's depth_score AFTER step 2, ``manifest`` = the curate
         stage's per-region ``RegionContentManifest``, accumulating
         ``threads_already_lit`` across ALL set-pieces in the WHOLE
         expansion. ``attach_set_piece`` emits its own
         ``setpiece.attach``/``trope.start``/``quest.seed`` spans and Plan 5
         emits ``ledger.add`` — Plan 7 does NOT re-emit them; they nest
         INSIDE this ``dungeon.materialize.attach`` span automatically.

    Invariants (No Silent Fallbacks):
    - ``graph``/``expansion``/``palette``/``curation``/``snapshot``/
      ``persistence`` must be real objects — ``None`` is rejected loudly.
      ``pack_tropes`` is a duck-typed object (``.tropes``) threaded from the
      session (Task 7 sources it in production) — REQUIRED, no default.
    - A region whose ``theme`` is absent from ``palette.themes`` → loud
      ``ValueError`` (no skip, no default theme).
    - A region absent from ``curation.region_manifests`` → loud
      ``KeyError`` via ``RegionCuration``'s fail-loud contract is NOT used
      here (it has no manifests accessor); we index ``region_manifests``
      directly and a ``KeyError`` propagates loudly (curate must cover
      every region — pipeline-ordering contract).
    - ``attach_expansion`` / ``assign_depth_scores`` / ``attach_set_piece``
      loud raises propagate unchanged after a routed failure marker is set.

    Returns an :class:`AttachResult` carrying the ``DepthReport`` and the
    per-(region, set_piece) ``AttachReport``s (each with ``.rolled`` — the
    spec §7 freeze target Task 6 persists, NEVER recomputed here). The
    attach stage does NOT commit / does NOT roll back / does NOT apply to a
    save — that is Task 6 (commit).
    """
    if graph is None:
        raise ValueError(
            "_stage_attach requires a real RegionGraph — "
            "graph=None is not valid (No Silent Fallbacks)"
        )
    if expansion is None:
        raise ValueError(
            "_stage_attach requires a real Expansion — "
            "expansion=None is not valid (No Silent Fallbacks)"
        )
    if palette is None:
        raise ValueError(
            "_stage_attach requires a real ThemePalette — "
            "palette=None is not valid (No Silent Fallbacks)"
        )
    if curation is None:
        raise ValueError(
            "_stage_attach requires the curate stage result — "
            "curation=None is not valid (No Silent Fallbacks)"
        )
    if snapshot is None:
        raise ValueError(
            "_stage_attach requires a real GameSnapshot — "
            "snapshot=None is not valid (No Silent Fallbacks). Production "
            "sourcing is the Task-7 session-wiring concern."
        )
    if pack_tropes is None:
        raise ValueError(
            "_stage_attach requires the resolved genre-pack tropes — "
            "pack_tropes=None is not valid (No Silent Fallbacks). "
            "Production sourcing is the Task-7 session-wiring concern."
        )
    if tx is None:
        raise ValueError(
            "_stage_attach requires the open DungeonTransaction — "
            "tx=None is not valid (No Silent Fallbacks). ADR-115 D6: attach "
            "threads ride the SAME txn the commit stage commits, so an attach "
            "thread + a commit_expansion PersistError roll back together."
        )

    # Step 1: attach_expansion — mutates + re-verifies the GLOBAL
    # connected + loopful invariants. A loud raise here ABORTS the whole
    # materialization: no depth scoring, no set-piece attach, no partial
    # state. Route the failure marker onto the span before re-raise.
    try:
        attach_expansion(graph, expansion)
    except (ValueError, KeyError) as exc:
        span.set_attribute("error", str(exc))
        span.set_attribute("reason", f"attach_expansion: {exc}")
        raise

    # Step 2: assign_depth_scores — entrance == 0.0 (no jitter), frozen
    # (already-scored regions never recomputed — spec §7). A to-be-scored
    # region unreachable on the ordinary route raises loudly.
    try:
        depth_report = assign_depth_scores(graph, campaign_seed=request.campaign_seed)
    except (ValueError, KeyError) as exc:
        span.set_attribute("error", str(exc))
        span.set_attribute("reason", f"assign_depth_scores: {exc}")
        raise

    # Byte-pinned span attribute contract: EXACTLY DepthReport.as_dict()'s
    # 4 scalar keys (NOT AttachReport — that is Plan 6's nested span).
    for k, v in depth_report.as_dict().items():
        span.set_attribute(k, v)

    # Step 3: for each region's theme, call Plan 6's coalescence entry point.
    # threads_already_lit accumulates across ALL set-pieces in the WHOLE
    # expansion (expansion-level budget — initialised once, never per-region).
    attach_reports: list[AttachReport] = []
    threads_already_lit = 0
    try:
        for node in expansion.new_nodes:
            if node.theme not in palette.themes:
                raise ValueError(
                    f"region {node.id!r} references theme {node.theme!r} "
                    f"which is absent from the palette (have: "
                    f"{sorted(palette.themes)}). No silent default theme."
                )
            theme = palette.themes[node.theme]
            # curate must cover every region (pipeline-ordering contract);
            # a missing manifest is a loud KeyError, not a silent default.
            manifest = curation.region_manifests[node.id]
            # depth_score AFTER assign_depth_scores ran (REQUIRED, no
            # default — Decision I in setpiece_attach).
            started_at_depth_score = graph.nodes[node.id].depth_score
            if started_at_depth_score is None:
                raise ValueError(
                    f"region {node.id!r} has no depth_score after "
                    f"assign_depth_scores — cannot attach set-pieces "
                    f"(No Silent Fallbacks)"
                )
            for set_piece in theme.set_pieces:
                report = attach_set_piece(
                    campaign_seed=request.campaign_seed,
                    expansion_id=request.expansion_id,
                    region_id=node.id,
                    setpiece_id=set_piece.id,
                    set_piece=set_piece,
                    trope_components=set_piece.trope_components,
                    quest_components=set_piece.quest_components,
                    pack_tropes=pack_tropes,
                    snapshot=snapshot,
                    manifest=manifest,
                    store=tx,
                    threads_lit_per_expansion=request.burst_magnitude,
                    threads_already_lit=threads_already_lit,
                    started_at_depth_score=started_at_depth_score,
                )
                threads_already_lit += report.threads_written
                attach_reports.append(report)

        # Task 7: seed the per-expansion quest thread from the deepest
        # region's theme (consistent with select_signature's _deepest —
        # the deepest region anchors the quest signature beat).
        # Guard: a no-op when the theme has no quest_template (not every
        # theme authors a quest; absence is valid, not an error).
        deepest_node = _expansion_deepest(expansion)
        if deepest_node.theme not in palette.themes:
            raise ValueError(
                f"deepest region {deepest_node.id!r} references theme "
                f"{deepest_node.theme!r} which is absent from the palette "
                f"(have: {sorted(palette.themes)}). No silent default theme."
            )
        deepest_theme = palette.themes[deepest_node.theme]
        if deepest_theme.quest_template is not None:
            deepest_depth_score = graph.nodes[deepest_node.id].depth_score
            if deepest_depth_score is None:
                raise ValueError(
                    f"deepest region {deepest_node.id!r} has no depth_score "
                    f"after assign_depth_scores — cannot seed expansion quest "
                    f"(No Silent Fallbacks)"
                )
            seed_expansion_quest(
                campaign_seed=request.campaign_seed,
                expansion=expansion,
                manifests_by_region=curation.region_manifests,
                template=deepest_theme.quest_template,
                store=tx,
                started_at_depth_score=deepest_depth_score,
            )
    except (ValueError, KeyError, PersistError) as exc:
        span.set_attribute("error", str(exc))
        span.set_attribute("reason", f"attach_stage: {exc}")
        raise

    return AttachResult(
        depth_report=depth_report,
        attach_reports=attach_reports,
    )


def _frontier_edge_id(campaign_seed: int, expansion_id: int, region_id: str) -> str:
    """Deterministic, collision-safe frontier-edge id.

    Mirrors ``setpiece_attach._thread_id_seed`` /
    ``region_graph.generator._subseed`` exactly: a pipe-delimited UTF-8
    string → ``blake2b(digest_size=8)`` → hex. NOT a uuid (a frontier
    re-derived from the same attached expansion must produce the SAME id
    so ``put_frontier``'s ``INSERT OR REPLACE`` is idempotent rather than
    duplicating rows). The house mixer; we do not invent a new scheme.
    """
    digest = hashlib.blake2b(
        f"frontier|{campaign_seed}|{expansion_id}|{region_id}".encode(),
        digest_size=8,
    ).digest()
    return f"fe_{digest.hex()}"


def _new_frontier_edges(
    request: MaterializationRequest,
    *,
    expansion: Expansion,
    graph: RegionGraph,
) -> list[FrontierEdge]:
    """Derive the new unexpanded frontier edges from the just-attached
    expansion (spec §7: "frontier — the set of unexpanded edges and the
    heading/depth_score an expansion there would spawn at").

    Each region node introduced by this expansion is a boundary from
    which a *future* expansion can be pushed outward — so each becomes a
    new unexpanded frontier edge:

    - ``from_region_id`` = the new region's id (the push-off point),
    - ``heading``        = the party's push heading (``request.heading``;
      the only directional signal the pipeline carries — spec §6's
      look-ahead "single approaching edge along the party's current
      heading"),
    - ``spawn_depth_score`` = that region's frozen ``depth_score`` after
      ``assign_depth_scores`` (the depth the *next* expansion off this
      region begins at — the gradient continues outward from here).

    No arbitrary edges are invented: every returned edge is anchored to a
    real ``expansion.new_nodes`` region whose depth_score the attach stage
    already froze onto ``graph.nodes`` (REQUIRED — a node with no
    depth_score is a loud reconcile failure, never a silent 0.0).
    """
    edges: list[FrontierEdge] = []
    for node in expansion.new_nodes:
        live = graph.nodes.get(node.id)
        if live is None:
            raise PersistError(
                f"new frontier edge derivation: region {node.id!r} is not in "
                f"the attached graph — commit must run after attach_expansion "
                f"(No Silent Fallbacks)"
            )
        if live.depth_score is None:
            raise PersistError(
                f"new frontier edge derivation: region {node.id!r} has no "
                f"depth_score after assign_depth_scores — cannot derive the "
                f"spawn_depth_score for the next expansion (No Silent "
                f"Fallbacks; never default to 0.0)"
            )
        edges.append(
            FrontierEdge(
                frontier_edge_id=_frontier_edge_id(
                    request.campaign_seed, request.expansion_id, node.id
                ),
                from_region_id=node.id,
                heading=request.heading,
                spawn_depth_score=live.depth_score,
            )
        )
    return edges


def _stage_tactical(
    *,
    expansion: Expansion,
    graph: RegionGraph,
    fill_result: Mapping[str, RegionFill],
    curation: RegionCuration,
    attach_result: AttachResult,
) -> dict[str, RegionTactical]:
    """Derive deterministic tactical data per filled region (ADR-096 token+feature).

    Thin adapter over ``derive_region_tactical``: pulls neighbours from the
    graph, theme from each region node, attached set-pieces from the attach
    reports, and creature counts from curation.  Pure given its inputs;
    placement is seeded by region_id inside the derivation (no random/clock).
    Only regions that carry a mask (``fill.mask is not None``) get a tactical
    record — matching the mask-persist set so there is never a tactical record
    for a region whose mask was not stored.
    """
    out: dict[str, RegionTactical] = {}
    for node in expansion.new_nodes:
        fill = fill_result.get(node.id)
        if fill is None or fill.mask is None:
            continue
        hazard_setpieces = [
            r.setpiece_id for r in attach_result.attach_reports if r.region_id == node.id
        ]
        out[node.id] = derive_region_tactical(
            region_id=node.id,
            grid=fill.grid,
            theme_key=node.theme,
            neighbor_ids=list(graph.neighbors(node.id)),
            hazard_setpieces=hazard_setpieces,
            creature_count=len(curation.region_creatures.get(node.id, [])),
        )
    return out


def _tactical_into_mask_dicts(
    mask_dicts: dict[str, dict],
    tactical: dict[str, RegionTactical],
) -> dict[str, dict]:
    """Merge each region's tactical record into its mask dict under ``tactical``.

    Mutates ``mask_dicts`` in place and returns it for chaining.

    Called inside ``_stage_commit`` immediately after ``expansion_masks`` is
    built and BEFORE ``tx.commit_expansion`` so the ``tactical`` key rides
    inside the existing mask JSON blob (no schema/DDL change — the merge
    happens in memory before JSON-encoding by the persistence layer).
    """
    for region_id, rt in tactical.items():
        if region_id in mask_dicts:
            mask_dicts[region_id]["tactical"] = rt.to_dict()
    return mask_dicts


def _stage_commit(
    request: MaterializationRequest,
    *,
    graph: RegionGraph | None,
    curation: RegionCuration | None,
    expansion: Expansion | None,
    attach_result: AttachResult | None,
    is_fresh_save: bool,
    tx: DungeonTransaction | None,
    span: _otel_trace.Span,
    fill_result: Mapping[str, RegionFill] | None = None,
) -> tuple[Path | None, dict[str, GeneratedRoomDescription]]:
    """Plan 7 Task 6: commit stage — rides the SAME transaction the attach
    stage wrote its threads into (ADR-115 D6), seed-as-Expansion-0, rollback
    on PersistError.

    The whole materialized expansion **plus its started threads** is
    written to the live save in ONE Plan 5 transaction and is
    *immediately live* on success (spec §7.5). The ``materialize()``
    coordinator owns the transaction boundary: it opens ONE
    ``dungeon_repository.transaction()`` spanning ``_stage_attach`` (which
    opened the complication threads on ``tx``) AND this stage. A
    ``commit_expansion`` PersistError therefore rolls back the attach-stage
    threads together with the expansion — NO half-attached expansion / NO
    orphan ledger (the Plan-5 atomicity contract). ``DungeonStore`` never
    autocommits.

    Sequence (all on ``persistence``'s connection, ONE txn):

    1. **Seed = Expansion 0** (loud fresh-save detection): production
       ``commit_expansion`` persists ONLY ``expansion.new_nodes``; the
       surface entrance has ``expansion_id == 0`` and belongs to NO
       generated ``Expansion.new_nodes``, so it is never persisted by a
       generated commit. On a *fresh* save (``is_fresh_save`` — the
       coordinator's loud ``load_map`` + ``load_frontier`` introspection,
       never assumed) the entrance is committed first as
       ``Expansion(expansion_id=0, new_nodes=[entrance], new_edges=[])``
       (entrance ``depth_score`` is the frozen root ``0.0``). On a
       non-fresh save the entrance is already frozen — re-committing it
       would (correctly) raise the freeze ``PersistError``; so the seed
       commit runs ONLY when the save is genuinely fresh.
    2. ``commit_expansion(expansion, graph)`` — persists this expansion's
       ``new_nodes``/``new_edges`` (depth-scored nodes read from
       ``graph``). A re-commit of an already-frozen region raises
       ``PersistError`` (spec §7 freeze — frozen regions never rewritten).
    3. RECONCILE SEAM A — the spec §7 FREEZE TARGET ``AttachReport.rolled``
       (a ``RolledSetPiece``) is persisted-as-is via the real Plan 5
       append-only primitive ``record_mutation(region_id,
       kind="setpiece_state", payload=...)`` within this SAME txn.
       ``commit_expansion``'s node payload (``RegionNode.to_dict()``) has
       NO setpiece-state slot and the ``mask BLOB`` column is unwritten by
       Plan 5's API, so ``record_mutation`` is the faithful Plan-5 carrier.
       ``.rolled`` is persisted EXACTLY as the attach stage produced it
       and is NEVER recomputed here (save-is-truth).
    4. New unexpanded frontier edges (derived from the attached expansion
       — :func:`_new_frontier_edges`, no invented edges) are
       ``put_frontier``'d within the same txn.
    5. The complication-ledger rows are ALREADY in this uncommitted
       transaction: ``_stage_attach`` called ``attach_set_piece`` →
       ``tx.open_thread`` on the SAME ``tx`` connection (ADR-115 D6). Task 6
       does NOT re-open threads; the txn it commits already contains them.

    On clean exit of the coordinator's ``with dungeon_repository.transaction()``
    the connection is committed → the expansion AND its threads are
    immediately live. On ``PersistError`` (``commit_expansion`` can write
    region A before region B's ``IntegrityError``) the outer
    ``transaction()`` context manager rolls the whole txn back — discarding
    the expansion rows, frontier edges, mutations AND the attach-stage
    threads together — so NO half-attached expansion / NO orphan ledger rows
    survive, then re-raises loudly (No Silent Fallbacks). A routed marker is
    set on the commit span (lie-detector visibility — the Task-2 lesson) and
    ``frontier.expand`` is emitted when the frontier is updated.

    Invariants (No Silent Fallbacks):
    - ``graph``/``expansion``/``curation``/``attach_result``/``tx``
      must be real objects — ``None`` is rejected loudly.
    - ``is_fresh_save`` is the coordinator's loud introspection (load_map +
      load_frontier), never an assumption.
    - ``PersistError`` → rollback + routed failure marker + re-raise; a
      partial/half-committed expansion is NEVER shipped.
    - ``AttachReport.rolled`` is persisted-as-is, NEVER recomputed.

    Returns ``(world_dir, composed_by_region)`` — the post-commit room-YAML
    emit data, computed here (under the txn) but written by the coordinator
    AFTER the txn commits so a rolled-back expansion deposits no orphan files
    (Story 55-1 invariant). ``world_dir`` is ``None`` when there is nothing to
    emit (no composed descriptions, or genre/world slug unset).
    """
    if graph is None:
        raise ValueError(
            "_stage_commit requires a real RegionGraph — "
            "graph=None is not valid (No Silent Fallbacks)"
        )
    if expansion is None:
        raise ValueError(
            "_stage_commit requires a real Expansion — "
            "expansion=None is not valid (No Silent Fallbacks)"
        )
    if curation is None:
        raise ValueError(
            "_stage_commit requires the curate stage result — "
            "curation=None is not valid (No Silent Fallbacks); the "
            "RegionCuration.region_manifests are the source of the "
            "cookbook-composed room_descriptions the post-commit YAML "
            "emit writes to <world>/rooms/<id>.yaml (Story 55-1)"
        )
    if attach_result is None:
        raise ValueError(
            "_stage_commit requires the attach stage result — "
            "attach_result=None is not valid (No Silent Fallbacks); the "
            "AttachReport.rolled freeze targets must be threaded by identity"
        )
    if tx is None:
        raise ValueError(
            "_stage_commit requires the open DungeonTransaction — tx=None is "
            "not valid (No Silent Fallbacks). ADR-115 D6: this stage writes "
            "into the SAME txn _stage_attach opened its threads on, so the "
            "expansion + its threads commit (or roll back) atomically."
        )

    # ADR-115 D6: the ``materialize()`` coordinator owns ONE
    # ``dungeon_repository.transaction()`` spanning BOTH _stage_attach (which
    # opened the complication threads on this ``tx``) and this stage. This
    # stage does NOT open its own transaction — it writes into the passed-in
    # ``tx`` and the coordinator's ``with`` block commits on clean exit / rolls
    # back on PersistError. Rolling back therefore discards the attach-stage
    # threads together with the expansion (Plan-5 atomicity: NO orphan ledger).
    #
    # ``is_fresh_save`` is the coordinator's loud introspection (load_map +
    # load_frontier both empty), computed BEFORE the txn opens so the txn holds
    # exactly one pooled connection for its lifetime (no transient second borrow
    # inside the with-block).

    # A bounded site (lookahead_breadth == 0) leaves NO open frontier edges —
    # it is materialized WHOLE, with no lookahead worker to expand it later
    # (Track B task 11). The frontier path (breadth >= 1) derives its edges as
    # before.
    new_frontier = (
        _new_frontier_edges(request, expansion=expansion, graph=graph)
        if request.lookahead_breadth > 0
        else []
    )

    # Resolve the generator version at COMMIT time, not at import time.
    # commit_expansion's `generator_version=GENERATOR_VERSION` default is
    # bound once at def-time; passing the current module global explicitly
    # honours a mid-campaign version bump so a genuinely never-materialized
    # expansion uses the new code while frozen regions stay frozen (spec
    # §7 "only never-materialized expansions use new code"). Read the live
    # module attribute (lazy-import idiom — the session.py watcher_hub
    # precedent — so a mid-campaign bump is observed, not the def-time
    # binding).
    from sidequest.dungeon import persistence as _live_persistence

    generator_version = _live_persistence.GENERATOR_VERSION

    try:
        if is_fresh_save:
            entrance = graph.nodes.get(graph.entrance_id)
            if entrance is None:
                raise PersistError(
                    f"Seed=Expansion-0: entrance {graph.entrance_id!r} is not "
                    f"in the graph — cannot seed a fresh save (No Silent "
                    f"Fallbacks)"
                )
            tx.commit_expansion(
                Expansion(expansion_id=0, new_nodes=[entrance], new_edges=[]),
                graph,
                generator_version=generator_version,
                site_id=request.site_id,
            )

        # Story 52-3 — thread fill-stage masks into the generated
        # expansion's commit (the materializer.py:57 gap). The seed
        # (Expansion 0) commit above passes NO masks: the entrance has
        # no fill grid (Seed=Expansion-0 contract). Regions whose
        # fill_result entry has no mask (e.g. test fixtures that
        # construct RegionFill directly) are absent from the masks
        # dict → their dungeon_map.mask BLOB stays NULL.
        expansion_masks: dict[str, dict] | None = None
        if fill_result is not None:
            expansion_masks = {
                rid: rf.mask.to_dict() for rid, rf in fill_result.items() if rf.mask is not None
            } or None

        # ADR-096 token+feature: derive deterministic tactical data and ride it
        # inside each region's mask dict (one JSON blob, no schema/DDL change).
        # Runs only when expansion_masks is non-None (fill results with masks
        # are available). No silent fallback — a derive error propagates and
        # rolls back the whole transaction (No Silent Fallbacks doctrine).
        if expansion_masks is not None:
            tactical = _stage_tactical(
                expansion=expansion,
                graph=graph,
                fill_result=fill_result,  # type: ignore[arg-type]
                curation=curation,
                attach_result=attach_result,
            )
            _tactical_into_mask_dicts(expansion_masks, tactical)
            with dungeon_materialize_tactical_span(
                region_count=len(tactical),
                feature_count=sum(len(rt.features) for rt in tactical.values()),
                anchor_count=sum(len(rt.anchors) for rt in tactical.values()),
            ):
                pass

        tx.commit_expansion(
            expansion,
            graph,
            generator_version=generator_version,
            masks=expansion_masks,
            site_id=request.site_id,
        )

        # RECONCILE SEAM A: persist the spec §7 freeze target
        # AttachReport.rolled EXACTLY as attach produced it (never
        # recomputed) via the real Plan 5 append-only primitive. One
        # mutation row per (region, set-piece) attach report.
        rolled_persisted = 0
        for report in attach_result.attach_reports:
            tx.record_mutation(
                report.region_id,
                "setpiece_state",
                {
                    "setpiece_id": report.setpiece_id,
                    "region_id": report.region_id,
                    "rolled": dict(report.rolled.slots),
                },
                site_id=request.site_id,
            )
            rolled_persisted += 1

        # Story 153-x: freeze each generated region's curated population on the
        # SAME txn (save-is-truth). Reuses the Plan-5 append-only primitive — no
        # new table. The entrance (Expansion 0) is authored content, not in
        # ``expansion.new_nodes``, so it is never given a procedural roster.
        pop_persisted = 0
        for node in expansion.new_nodes:
            roster = curation.region_creatures.get(node.id, [])
            big_bad = curation.region_big_bad.get(node.id)
            if not roster and big_bad is None:
                continue
            tx.record_mutation(
                node.id,
                "region_population",
                {
                    "region_id": node.id,
                    "creatures": [_curated_to_payload(c) for c in roster],
                    "big_bad": _curated_to_payload(big_bad) if big_bad is not None else None,
                },
                site_id=request.site_id,
            )
            pop_persisted += 1

        for fe in new_frontier:
            # Only the frontier path (lookahead_breadth > 0) ever reaches here —
            # a bounded site's new_frontier is empty (gated above), so it writes
            # no frontier edges. The frontier path is the DEFAULT_SITE_ID store,
            # so put_frontier's default site_id is correct and unthreaded.
            tx.put_frontier(fe)
        # The coordinator's ``with dungeon_repository.transaction()`` commits on
        # clean exit (after _stage_attach + _stage_commit) and rolls back on any
        # exception — no explicit conn.commit()/rollback() here.
    except PersistError as exc:
        span.set_attribute("error", str(exc))
        span.set_attribute("reason", f"commit: {exc}")
        raise

    # Lie-detector success summary on the commit span (the design/attach
    # precedent: a real success summary, not just the pre-baked stage).
    span.set_attribute("expansion_id", request.expansion_id)
    span.set_attribute("seeded_entrance", is_fresh_save)
    span.set_attribute("regions_committed", len(expansion.new_nodes))
    span.set_attribute("edges_committed", len(expansion.new_edges))
    span.set_attribute("rolled_persisted", rolled_persisted)
    span.set_attribute("region_populations_committed", pop_persisted)
    span.set_attribute("frontier_edges_added", len(new_frontier))
    span.set_attribute("generator_version", generator_version)

    # Plan 7 owns frontier.expand: emit one per new unexpanded frontier
    # edge so the GM panel sees the dungeon's frontier actually grew (the
    # OTEL Observability Principle — the frontier update must be
    # observable, not just asserted by narration). These fire after the
    # writes land in the txn; they are pure observability, so emitting
    # before the coordinator's COMMIT flush is fine (a PersistError above
    # propagates and skips them).
    for fe in new_frontier:
        with frontier_expand_span(
            expansion_id=request.expansion_id,
            frontier_edge_id=fe.frontier_edge_id,
            from_region_id=fe.from_region_id,
            heading=fe.heading,
            spawn_depth_score=fe.spawn_depth_score,
        ):
            pass

    # Story 55-1 / ADR-109 §5.2: per-region YAML emit data. The disk write
    # itself is the coordinator's job AFTER the tx commits — ADR-115 D6 made
    # the coordinator own the commit boundary, so a rolled-back expansion must
    # never deposit orphan files on disk. We compute the (world_dir,
    # composed_by_region) here (we hold curation/expansion) and return it so
    # the coordinator emits post-commit.
    composed_by_region: dict[str, GeneratedRoomDescription] = {}
    for node in expansion.new_nodes:
        manifest = curation.region_manifests.get(node.id)
        if manifest is None or not manifest.room_descriptions:
            continue
        composed_by_region[node.id] = manifest.room_descriptions[0]

    world_dir = _resolve_world_dir(request) if composed_by_region else None
    return world_dir, composed_by_region


def _stage_emit_room_yamls(
    *,
    world_dir: Path,
    composed_by_region: dict[str, GeneratedRoomDescription],
) -> None:
    """Story 55-1 / ADR-109 §5.2: write one ``<world_dir>/rooms/<id>.yaml``
    per region using the cookbook's composed ``(prose, entities[])``.

    Idempotent — existing YAMLs are NEVER overwritten (freeze invariant
    matches the rest of the Plan 7 commit stage; a re-materialization
    of a frozen region must not rewrite its content). The 54-3
    validator runs as a post-materialize CI smoke check on the emitted
    YAMLs once 54-3 lands.

    Empty ``composed_by_region`` is a clean no-op — no empty ``rooms/``
    directory is created.

    Runs **after** ``conn.commit()`` in the production caller so a
    rolled-back expansion never deposits orphan files on disk.
    """
    if not composed_by_region:
        return

    from sidequest.dungeon.room_yaml_emit import write_room_yaml

    rooms_dir = world_dir / "rooms"
    for region_id, composed in composed_by_region.items():
        target = rooms_dir / f"{region_id}.yaml"
        if target.exists():
            # Freeze invariant: a region whose YAML already exists is
            # left alone (re-materialization of a frozen region must
            # not rewrite content — ADR-106 §7). The skip is explicit,
            # not silent: the function docstring and this comment
            # document why.
            continue
        write_room_yaml(
            world_dir=world_dir,
            room_id=region_id,
            description=composed.description,
            entities=composed.entities,
            overwrite=False,
        )


def _resolve_world_dir(request: MaterializationRequest) -> Path | None:
    """Resolve ``<pack_root>/worlds/<world_slug>`` for the request.

    Returns ``None`` when ``genre_slug`` or ``world_slug`` is empty —
    this is the "test fixture didn't wire genre/world" path that
    intentionally suppresses the YAML emit (Story 55-1 deliberate seam,
    NOT a silent fallback: the explicit empty-string default on
    ``MaterializationRequest`` is the gate).
    """
    if not request.genre_slug or not request.world_slug:
        return None

    from sidequest.genre.loader import DEFAULT_GENRE_PACK_SEARCH_PATHS, GenreLoader

    loader = GenreLoader(search_paths=DEFAULT_GENRE_PACK_SEARCH_PATHS)
    pack_root = loader.find(request.genre_slug)
    world_dir = pack_root / "worlds" / request.world_slug
    # Only mirror rooms into a REAL authored world (one carrying a world.yaml).
    # A resolved dir with no world.yaml is not a world: persisting rooms there
    # mints a phantom ``worlds/<slug>/rooms`` dir that the genre loader then
    # rejects on its next load. In production every bound world ships a
    # world.yaml, so this never fires; it bites only the hermetic test fixture
    # tree, where a genre symlink resolves a world the fixture pack does not
    # author (and concurrent xdist workers race on that shared path). The
    # in-memory dungeon is unaffected — only the optional on-disk YAML mirror is
    # skipped. No Silent Fallbacks: we refuse to fabricate a world dir, we do not
    # silently write into the wrong tree. Tests that exercise the room-YAML mirror
    # itself pass an explicit world_dir to write_room_yaml/_stage_emit_room_yamls
    # and never reach here.
    if not (world_dir / "world.yaml").is_file():
        return None
    return world_dir


def _commit_bounded(
    request: MaterializationRequest,
    *,
    graph: RegionGraph,
    expansion: Expansion,
    fill_result: Mapping[str, RegionFill],
    tactical: dict[str, RegionTactical],
    room_identities: dict[str, dict],
    is_fresh_save: bool,
    tx: DungeonTransaction,
    span: _otel_trace.Span,
) -> None:
    """ADR-157 geometry commit for a bounded site — cookbook-free.

    Persists Seed=Expansion-0 (entrance) on a fresh site store, the room
    expansion + per-room masks (with tactical merged into the mask blob), and
    one ``room_identity`` mutation per labelled room. Writes NO frontier edges
    (a bounded site has lookahead_breadth == 0), NO ``region_population`` and NO
    ``setpiece_state`` (zero engine-placed creatures / set-pieces). Rides the
    caller's ``tx``; the coordinator's ``with transaction()`` commits/rolls back.
    """
    from sidequest.dungeon import persistence as _live_persistence

    generator_version = _live_persistence.GENERATOR_VERSION
    try:
        if is_fresh_save:
            entrance = graph.nodes.get(graph.entrance_id)
            if entrance is None:
                raise PersistError(
                    f"Seed=Expansion-0: entrance {graph.entrance_id!r} is not in "
                    f"the graph — cannot seed a fresh bounded site (No Silent Fallbacks)"
                )
            tx.commit_expansion(
                Expansion(expansion_id=0, new_nodes=[entrance], new_edges=[]),
                graph,
                generator_version=generator_version,
                site_id=request.site_id,
            )

        expansion_masks: dict[str, dict] | None = {
            rid: rf.mask.to_dict() for rid, rf in fill_result.items() if rf.mask is not None
        } or None
        if expansion_masks is not None:
            _tactical_into_mask_dicts(expansion_masks, tactical)

        tx.commit_expansion(
            expansion,
            graph,
            generator_version=generator_version,
            masks=expansion_masks,
            site_id=request.site_id,
        )

        identities_written = 0
        for node in expansion.new_nodes:
            payload = room_identities.get(node.id)
            if payload is None:
                continue
            tx.record_mutation(node.id, "room_identity", payload, site_id=request.site_id)
            identities_written += 1
    except PersistError as exc:
        span.set_attribute("error", str(exc))
        span.set_attribute("reason", f"commit_bounded: {exc}")
        raise

    span.set_attribute("expansion_id", request.expansion_id)
    span.set_attribute("seeded_entrance", is_fresh_save)
    span.set_attribute("regions_committed", len(expansion.new_nodes))
    span.set_attribute("edges_committed", len(expansion.new_edges))
    span.set_attribute("room_identities_committed", identities_written)
    span.set_attribute("frontier_edges_added", 0)
    span.set_attribute("generator_version", generator_version)


