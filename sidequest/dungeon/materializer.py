async def materialize(
    request: MaterializationRequest,
    *,
    graph: RegionGraph | None,
    bundle: Any,
    palette: Any,
    dungeon_repository: DungeonRepository,
    snapshot: GameSnapshot,
    pack_tropes: Any,
    is_first_band_entry: bool = True,
    pack: Any = None,
) -> None:
    """Run the five-stage materialisation pipeline for one expansion.

    Opens a parent ``dungeon.materialize`` OTEL span; each of the five stage
    spans nests under it in order (design → fill → curate → attach → commit).

    Stages design/fill/curate are implemented (Plan 7 Tasks 2–4); attach
    and commit remain ``NotImplementedError`` until Plan 7 Tasks 5–6.

    ``async def``: ADR-106 Amendment C removed the LLM from curate, so all
    five stages are now synchronous and the coordinator awaits nothing
    internally. ``materialize`` stays ``async def`` only so the existing
    ``await materialize()`` call sites (session integration, the look-ahead
    worker's coroutine, the suite) are unchanged; collapsing the coordinator
    + worker to synchronous calls is a separable fast-follow (158-12 AC7).

    Parameters
    ----------
    request:
        Frozen expansion specification. ``request.expansion_id`` must be >= 1.
    graph:
        The live ``RegionGraph`` (passed through to attach/commit stages).
    bundle:
        The cookbook bundle (consumed by the curate stage).
    palette:
        The ``ThemePalette`` (consumed by design/fill/curate).
    dungeon_repository:
        The ``DungeonRepository`` (PgDungeonRepository) for the session.
        The commit stage uses ``transaction()`` to write atomically.
    snapshot:
        The live ``GameSnapshot`` — the attach stage's
        ``attach_set_piece`` call mutates ``snapshot.active_tropes`` for
        every started trope component (ADR-018 seam). REQUIRED, no silent
        default. Production sourcing (the live session snapshot) is the
        Task-7 session-wiring concern; Task 5 binds the API.
        (Reconcile seam: ``snapshot``.)
    pack_tropes:
        The resolved genre-pack tropes (a duck-typed object with
        ``.tropes``, ADR-018) threaded into the attach stage's
        ``attach_set_piece`` call so trope_ids resolve against the pack.
        REQUIRED, no silent default. Production sourcing (the resolved
        genre-pack) is the Task-7 session-wiring concern; Task 5 binds the
        API. (Reconcile seam: ``pack_tropes``.)
    is_first_band_entry:
        Caller-asserted band-entry flag threaded into the curate stage's
        ``assemble_region`` call. The TRUE band-entry-history computation
        needs Plan 5 persistence (``load_frontier``/``load_map``) that the
        curate stage does NOT own; it is deferred to Task 6 (commit, which
        owns persistence). For Task 4 the coordinator passes this
        caller-supplied value (NOT a silent default computed from
        incomplete state). (Reconcile seam: ``is_first_band_entry``.)
    """
    if graph is None:
        raise ValueError(
            "materialize requires a real RegionGraph — graph=None is not valid "
            "(No Silent Fallbacks); the coordinator reads graph.entrance_id for "
            "fresh-save detection and every stage threads it"
        )

    # The per-region look is derived from each region's theme INSIDE
    # _stage_curate (it has bundle+palette+expansion) — the theme is the
    # single source of truth (loud raise on unresolvable/multi-bound;
    # never a silent default). No look value is threaded from here.
    with dungeon_materialize_span(
        expansion_id=request.expansion_id,
        heading=request.heading,
        burst_magnitude=request.burst_magnitude,
    ):
        with dungeon_materialize_design_span(expansion_id=request.expansion_id) as design_span:
            expansion, _report = _stage_design(
                request, graph=graph, palette=palette, span=design_span
            )

        with dungeon_materialize_fill_span(expansion_id=request.expansion_id) as fill_span:
            fill_result = _stage_fill(request, expansion=expansion, palette=palette, span=fill_span)

        with dungeon_materialize_curate_span(expansion_id=request.expansion_id) as curate_span:
            # ADR-106 Amendment C: curate is deterministic seeded compute —
            # no LLM, no await. The narrator owns creature prose at narration.
            curation = _stage_curate(
                request,
                bundle=bundle,
                palette=palette,
                expansion=expansion,
                fill_result=fill_result,
                is_first_band_entry=is_first_band_entry,
                span=curate_span,
                pack=pack,
            )

        # Loud fresh-save detection (introspection, NOT an assumption): a save
        # is fresh iff the dungeon map AND frontier are both empty. On a fresh
        # save the surface entrance has never been persisted (it belongs to no
        # generated Expansion.new_nodes) so _stage_commit must seed it as
        # Expansion 0 before the first generated expansion is committed. These
        # reads run BEFORE the txn opens so the txn holds exactly ONE pooled
        # connection for its lifetime — the seed race is still caught loudly by
        # the Expansion-0 freeze PersistError, and per-session materialization
        # is already serialized.
        existing_map = dungeon_repository.load_map(
            entrance_id=graph.entrance_id, site_id=request.site_id
        )
        existing_frontier = dungeon_repository.load_frontier(site_id=request.site_id)
        is_fresh_save = not existing_map.nodes and not existing_frontier

        # ADR-115 D6: ONE transaction spans BOTH _stage_attach (which opens
        # the complication threads on ``tx``) and _stage_commit (which writes
        # the expansion/frontier/mutations on the SAME ``tx``). A
        # commit_expansion PersistError therefore rolls back the attach-stage
        # threads together with the expansion — restoring the Plan-5 atomicity
        # contract (NO half-attached expansion / NO orphan ledger). Both stages
        # are SYNC and run back-to-back with NO ``await`` between them, so the
        # pooled connection is never held across an await/LLM call (the async
        # curate stage already ran, above, OUTSIDE this txn).
        with dungeon_repository.transaction() as tx:
            with dungeon_materialize_attach_span(expansion_id=request.expansion_id) as attach_span:
                attach_result = _stage_attach(
                    request,
                    graph=graph,
                    expansion=expansion,
                    palette=palette,
                    curation=curation,
                    snapshot=snapshot,
                    pack_tropes=pack_tropes,
                    tx=tx,
                    span=attach_span,
                )

            with dungeon_materialize_commit_span(expansion_id=request.expansion_id) as commit_span:
                # Thread the attach stage's AttachResult into commit: its
                # ``attach_reports[].rolled`` is the spec §7 freeze target Task
                # 6 PERSISTS and NEVER recomputes (save-is-truth). Discarding
                # it here would force Task 6 to re-roll. ``expansion``/``graph``
                # carry the depth-scored attached topology commit_expansion +
                # new-frontier-edge derivation read. ``_stage_commit`` is SYNC
                # (commit_expansion/put_frontier are sync) — a plain call inside
                # this async coordinator, never awaited. It returns the
                # post-commit YAML-emit data (computed under the txn) so the
                # disk write runs only AFTER a clean commit, below.
                world_dir, composed_by_region = _stage_commit(
                    request,
                    graph=graph,
                    curation=curation,
                    expansion=expansion,
                    attach_result=attach_result,
                    is_fresh_save=is_fresh_save,
                    tx=tx,
                    span=commit_span,
                    fill_result=fill_result,
                )
        # The txn committed on clean exit of the ``with`` above (or rolled the
        # whole attach+commit back on PersistError). The per-region room YAMLs
        # are written ONLY now — after a clean commit — so a rolled-back
        # expansion never deposits orphan files on disk (Story 55-1 invariant).
        if world_dir is not None and composed_by_region:
            _stage_emit_room_yamls(
                world_dir=world_dir,
                composed_by_region=composed_by_region,
            )


def _bounded_room_identities(
    archetype: Any,
    *,
    campaign_seed: int,
    site_id: str,
    region_ids: list[str],
) -> dict[str, dict]:
    """Deterministically label each bounded room from the archetype vocabulary.

    ADR-157: the archetype's ``room_vocabulary`` gives each generated room an
    identity ("common room", "cellar") and up to two ``feature_palette`` props —
    Diamonds-and-Coal, not anonymous cells. Seeded by ``blake2b(campaign_seed,
    site_id, region_id)`` (the house mixer) so re-entry reproduces the same
    labels. An archetype with an empty ``room_vocabulary`` yields ``{}`` (a valid
    label-less site, not a silent default).
    """
    vocab = list(archetype.room_vocabulary)
    if not vocab:
        return {}
    features = list(archetype.feature_palette)
    out: dict[str, dict] = {}
    for rid in region_ids:
        digest = hashlib.blake2b(
            f"roomid|{campaign_seed}|{site_id}|{rid}".encode(), digest_size=8
        ).digest()
        mix = int.from_bytes(digest, "big")
        label = vocab[mix % len(vocab)]
        chosen: list[str] = []
        if features:
            # Deterministic, stable subset (up to 2), no RNG.
            start = mix % len(features)
            take = min(2, len(features))
            chosen = [features[(start + i) % len(features)] for i in range(take)]
        out[rid] = {"region_id": rid, "label": label, "features": chosen}
    return out


async def materialize_bounded(
    request: MaterializationRequest,
    *,
    graph: RegionGraph,
    palette: ThemePalette,
    dungeon_repository: DungeonRepository,
    archetype: Any,
) -> None:
    """ADR-157: materialize a bounded site's WHOLE interior, cookbook-free.

    A parallel coordinator to ``materialize`` for ``extent: bounded`` sites. It
    reuses the two already-cookbook-free geometry stages (design + fill), does a
    STRUCTURAL graph finalize (``attach_expansion`` + ``assign_depth_scores`` —
    the connectivity/depth primitives, NOT the set-piece/trope/quest attach
    stage), derives monster-free tactical data, and runs the dedicated geometry
    commit. There is NO ``CookbookBundle`` in the signature: a bounded site needs
    no world ``cookbook/``/``corpus/``/``themes/``/``world_register.yaml``.

    Grid dims stay the 49×49 default (per-archetype sizing is Track B4). Zero
    engine-placed creatures — inhabitants come from the Living World.

    ``async def`` mirrors ``materialize`` (call-site symmetry); it awaits nothing
    internally.
    """
    with dungeon_materialize_span(
        expansion_id=request.expansion_id,
        heading=request.heading,
        burst_magnitude=request.burst_magnitude,
    ):
        with dungeon_materialize_design_span(expansion_id=request.expansion_id) as design_span:
            # ADR-157: honor the archetype's declared room budget instead of the
            # frontier default new_regions_per_expansion. _stage_design guards a
            # None graph loudly, so no separate guard is needed here.
            expansion, _report = _stage_design(
                request,
                graph=graph,
                palette=palette,
                span=design_span,
                region_count=(archetype.room_count_min, archetype.room_count_max),
            )

        with dungeon_materialize_fill_span(expansion_id=request.expansion_id) as fill_span:
            fill_result = _stage_fill(request, expansion=expansion, palette=palette, span=fill_span)

        # STRUCTURAL graph finalize (NOT the set-piece attach stage): add the
        # new nodes/edges to the graph and freeze depth scores so the committed
        # graph is connected + depth-scored exactly like the frontier path's,
        # minus the monster content. attach_expansion re-verifies the global
        # connected+loopful invariants (loud raise aborts the whole run).
        attach_expansion(graph, expansion)
        assign_depth_scores(graph, campaign_seed=request.campaign_seed)

        # Monster-free tactical: no set-piece hazards, no creature tokens.
        tactical: dict[str, RegionTactical] = {}
        for node in expansion.new_nodes:
            fill = fill_result.get(node.id)
            if fill is None or fill.mask is None:
                continue
            tactical[node.id] = derive_region_tactical(
                region_id=node.id,
                grid=fill.grid,
                theme_key=node.theme,
                neighbor_ids=list(graph.neighbors(node.id)),
                hazard_setpieces=[],
                creature_count=0,
            )

        room_identities = _bounded_room_identities(
            archetype,
            campaign_seed=request.campaign_seed,
            site_id=request.site_id,
            region_ids=[node.id for node in expansion.new_nodes],
        )

        existing_map = dungeon_repository.load_map(
            entrance_id=graph.entrance_id, site_id=request.site_id
        )
        existing_frontier = dungeon_repository.load_frontier(site_id=request.site_id)
        is_fresh_save = not existing_map.nodes and not existing_frontier

        with (
            dungeon_repository.transaction() as tx,
            dungeon_materialize_commit_span(expansion_id=request.expansion_id) as commit_span,
        ):
            _commit_bounded(
                request,
                graph=graph,
                expansion=expansion,
                fill_result=fill_result,
                tactical=tactical,
                room_identities=room_identities,
                is_fresh_save=is_fresh_save,
                tx=tx,
                span=commit_span,
            )
